// Copies the NM design tokens the receiver reads from app-web's generated tokens.css.
// Usage: node scripts/sync-nm-tokens.mjs <app-web tokens.css> [--report]
// Writes src/styles/nm-tokens.css: the dark :root block only, the --nm-* names the
// source files read (plus what those names reference), color-mix() resolved to rgba()
// because the Cast device browser (Chrome 92) cannot read it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src/styles/nm-tokens.css');
const MODERN = /(?<![\w-])(?:oklch|oklab|lab|lch|color-mix)\(|@layer\b/;
const DECLARATION = /(--[\w-]+)\s*:([^;]+);/g;
const REPORT_DECL = /--[\w-]+:(.+);/;
const VAR_REF = /^var\((--[\w-]+)\)$/;
const VAR_USE = /var\((--[\w-]+)/g;
const NM_USE = /var\((--nm-[\w-]+)/g;
const HEX = /^#([0-9a-f]{3,8})$/i;
const RGBA = /^rgba?\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)$/;
const SPACES = /\s+/g;
const ROOT_BLOCK = /^:root \{$/m;
const SOURCE_FILE = /\.(?:vue|css|ts)$/;
const TEST_FILE = /\.(?:test|spec)\./;

export function declarations(body) {
	const out = new Map();
	for (const m of body.matchAll(DECLARATION))
		out.set(m[1], m[2].replace(SPACES, ' ').trim());
	return out;
}

function toRgba(value, vars, seen = new Set()) {
	const v = value.trim();
	const ref = VAR_REF.exec(v);
	if (ref) {
		if (seen.has(ref[1]) || !vars.has(ref[1]))
			throw new Error(`cannot resolve ${v}`);
		return toRgba(vars.get(ref[1]), vars, new Set([...seen, ref[1]]));
	}
	const hex = HEX.exec(v);
	if (hex) {
		let h = hex[1];
		if (h.length <= 4)
			h = [...h].map(c => c + c).join('');
		const n = [0, 2, 4].map(i => Number.parseInt(h.slice(i, i + 2), 16));
		return [...n, h.length === 8 ? Number.parseInt(h.slice(6, 8), 16) / 255 : 1];
	}
	const fn = RGBA.exec(v.replaceAll(' ', ''));
	if (fn)
		return [Number(fn[1]), Number(fn[2]), Number(fn[3]), fn[4] === undefined ? 1 : Number(fn[4])];
	if (v.startsWith('color-mix(') && v.endsWith(')')) {
		const [space, mixed, rest] = v.slice('color-mix('.length, -1).split(',').map(s => s.trim());
		const cut = mixed.lastIndexOf(' ');
		if (space !== 'in srgb' || rest !== 'transparent' || cut < 0 || !mixed.endsWith('%'))
			throw new Error(`cannot resolve ${v}`);
		const [r, g, b, a] = toRgba(mixed.slice(0, cut), vars, seen);
		return [r, g, b, a * Number(mixed.slice(cut + 1, -1)) / 100];
	}
	throw new Error(`cannot resolve ${v}`);
}

// Replaces each color-mix(...) call in a value with the rgba() it computes.
export function resolveModern(value, vars) {
	let out = value;
	for (let at = out.indexOf('color-mix('); at >= 0; at = out.indexOf('color-mix(')) {
		let depth = 0;
		let end = at;
		for (; end < out.length; end++) {
			if (out[end] === '(')
				depth++;
			if (out[end] === ')' && --depth === 0)
				break;
		}
		const [r, g, b, a] = toRgba(out.slice(at, end + 1), vars);
		out = `${out.slice(0, at)}rgba(${r}, ${g}, ${b}, ${Number(a.toFixed(3))})${out.slice(end + 1)}`;
	}
	return out;
}

function darkRoot(css) {
	const start = css.search(ROOT_BLOCK);
	if (start < 0)
		throw new Error('no plain :root block in the source');
	return css.slice(start, css.indexOf('\n}', start));
}

function sourceFiles(dir) {
	return readdirSync(dir, { recursive: true, withFileTypes: true })
		.filter(e => e.isFile() && SOURCE_FILE.test(e.name) && !TEST_FILE.test(e.name))
		.map(e => join(e.parentPath, e.name))
		.filter(f => !f.endsWith('nm-tokens.css'));
}

export function usedNames(dir) {
	const names = new Set();
	for (const f of sourceFiles(dir)) {
		for (const m of readFileSync(f, 'utf8').matchAll(NM_USE))
			names.add(m[1]);
	}
	return names;
}

export function build(source, used) {
	const vars = declarations(darkRoot(source));
	const need = new Set();
	const add = (name) => {
		if (need.has(name))
			return;
		if (!vars.has(name))
			throw new Error(`${name} is not in the source :root block`);
		need.add(name);
		for (const m of vars.get(name).matchAll(VAR_USE))
			add(m[1]);
	};
	used.forEach(add);
	const lines = [...vars].filter(([n]) => need.has(n)).map(([n, v]) => `\t${n}: ${resolveModern(v, vars)};`);
	return [
		'/* Generated by scripts/sync-nm-tokens.mjs from app-web src/components/nm/tokens.css (dark :root).',
		' * Do not edit: run the script again. Only the names the receiver reads are copied. */',
		':root {',
		...lines,
		'}',
		'',
	].join('\n');
}

function indentOf(line) {
	return line.length - line.trimStart().length;
}

function report(source) {
	const vars = declarations(darkRoot(source));
	const lines = source.split('\n');
	let hits = 0;
	lines.forEach((line, i) => {
		if (!MODERN.test(line))
			return;
		hits++;
		const decl = REPORT_DECL.exec(line.trim());
		let resolved = 'not a declaration';
		if (decl) {
			try {
				// The enclosing block answers for its own accent step (light, dark, light media query).
				let from = i;
				while (from > 0 && !(lines[from].trimEnd().endsWith('{') && indentOf(lines[from]) < indentOf(line)))
					from--;
				let to = i;
				while (to < lines.length - 1 && !(lines[to].trim() === '}' && indentOf(lines[to]) === indentOf(lines[from])))
					to++;
				const own = declarations(lines.slice(from + 1, to).join('\n'));
				resolved = resolveModern(decl[1].trim(), new Map([...vars, ...own]));
			}
			catch (error) {
				resolved = String(error.message);
			}
		}
		console.log(`${i + 1}: ${line.trim()}\n   -> ${resolved}`);
	});
	console.log(`${hits} lines with oklch, color-mix, lab or @layer`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const file = process.argv[2];
	if (!file) {
		console.error('usage: node scripts/sync-nm-tokens.mjs <app-web tokens.css> [--report]');
		process.exit(2);
	}
	const source = readFileSync(file, 'utf8');
	if (process.argv.includes('--report')) {
		report(source);
	}
	else {
		const css = build(source, usedNames(join(root, 'src')));
		if (MODERN.test(css))
			throw new Error('the output still holds oklch, color-mix, lab or @layer');
		writeFileSync(OUT, css);
		console.log(`sync-nm-tokens: ${css.split('\n').filter(l => l.startsWith('\t')).length} tokens, ${css.length} bytes -> src/styles/nm-tokens.css`);
	}
}
